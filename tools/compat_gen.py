"""Write lib/LibForever-1.0/CompatList.lua from this repo's relocated-API table (docs/compat.json).

    python tools/compat_gen.py

Takes the classic functions that are gone on WoW Forever and whose replacement is one function, verified in game,
called the same way with the same answers ("Same ..." in the table's notes), and lists them for LibForever.Compat, which
passes each call straight to the replacement. Functions Compat handles by hand (Compat.lua's MAP) are left
out, and so are entries whose notes ask for a check in game first. The rest of the table (calls that changed shape,
and old names that still work through Blizzard's deprecation add-ons) is docs/relocated.md to read.
"""

import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
LIB = os.path.join(ROOT, "lib", "LibForever-1.0")

# notes that say the answer changed ("returns a result code instead of true/false") or that ask for a check first
DOUBTFUL = re.compile(r"if it exists|check in game|before relying|instead of|result code", re.I)


def hand_kept():
    with open(os.path.join(LIB, "Compat.lua"), encoding="utf-8") as handle:
        block = handle.read().split("Compat.MAP = {", 1)[1].split("\n}", 1)[0]
    return set(re.findall(r"(\w+) = \"", block))


def main():
    api_dir = ROOT
    with open(os.path.join(api_dir, "docs", "compat.json"), encoding="utf-8") as handle:
        table = json.load(handle)
    with open(os.path.join(api_dir, "docs", "api.json"), encoding="utf-8") as handle:
        dump = json.load(handle)["functions"]
    by_hand = hand_kept()
    chosen, skipped = [], []
    for entry in table["entries"]:
        old, new, change = entry.get("old"), entry.get("new") or [], entry.get("change") or ""
        if entry.get("where") != "missing" or len(new) != 1 or entry.get("new_not_in_game"):
            continue
        if not change.startswith("Same") or old in by_hand:
            continue
        if DOUBTFUL.search(change) or (dump.get(new[0]) or {}).get("status") != "verified" or old in dump:
            skipped.append(old)
            continue
        chosen.append((old, new[0], change))
    chosen.sort()
    lines = [
        "-- Generated by tools/compat_gen.py from ForeverAPI's relocated-API table (client %s). Do not edit: run it again."
        % table.get("build", "?"),
        "-- Classic functions gone on WoW Forever whose replacement is called the same way with the same answers.",
        "-- LibForever.Compat (Compat.lua) adds each one, passing the call straight through.",
        "",
        'local LF = LibStub("LibForever-1.0", true)',
        "if not (LF and LF._loading) then return end",
        "",
        "LF.CompatSame = {",
    ]
    for old, new, change in chosen:
        note = change.split(". ")[0].rstrip(".")
        lines.append('  %s = "%s",   -- %s' % (old, new, note))
    lines.append("}")
    out = os.path.join(LIB, "CompatList.lua")
    with open(out, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines) + "\n")
    print("wrote %d functions to %s" % (len(chosen), out))
    if skipped:
        print("left out (a check in game first, or not verified): " + ", ".join(sorted(skipped)))


if __name__ == "__main__":
    main()
